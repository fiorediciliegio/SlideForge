const WORKSPACE_SNAPSHOT_APS_ROOT = "workspaces";
const RUNNING_PUBLISH_STATUSES: WorkspaceSnapshotPublishStatus[] = [
  "queued",
  "preparing",
  "uploading",
  "committing",
];

function apsSnapshotPath(workspaceId: string, revision: string): string {
  return `${WORKSPACE_SNAPSHOT_APS_ROOT}/${workspaceId}/snapshots/${revision}.zip`;
}

function apsMetaPath(workspaceId: string): string {
  return `${WORKSPACE_SNAPSHOT_APS_ROOT}/${workspaceId}/meta.json`;
}

function createInitialPublishState(workspaceDir: string): WorkspaceSnapshotPublishState {
  const now = new Date().toISOString();
  return {
    status: "idle",
    job_id: "",
    workspace_dir: workspaceDir,
    revision: null,
    aps_path: null,
    aps_meta_path: null,
    meta_json: null,
    snapshot_path: null,
    source_updated_at: null,
    source_sha256: null,
    fingerprint_algo: SNAPSHOT_FINGERPRINT_ALGO,
    snapshot_sha256: null,
    snapshot_size_bytes: null,
    file_count: 0,
    attachments: [],
    lifecycle_epoch: 0,
    change_seq: 0,
    last_synced_updated_at: null,
    last_synced_sha256: null,
    mirror: null,
    started_at: null,
    updated_at: now,
    completed_at: null,
    error: null,
  };
}

function normalizeSnapshotAttachments(value: unknown): WorkspaceSnapshotAttachment[] {
  if (!Array.isArray(value)) return [];
  const attachments = new Map<string, WorkspaceSnapshotAttachment>();
  for (const item of value) {
    if (!item || typeof item !== "object" || Array.isArray(item)) continue;
    const record = item as Record<string, unknown>;
    const contentHash = typeof record.content_hash === "string" ? record.content_hash.toLowerCase() : "";
    const size = typeof record.size_bytes === "number" && Number.isSafeInteger(record.size_bytes) && record.size_bytes >= 0
      ? record.size_bytes
      : null;
    const restorePath = typeof record.restore_path === "string" ? record.restore_path : "";
    if (!/^[a-f0-9]{64}$/.test(contentHash) || size === null || !restorePath) continue;
    try {
      const safePath = posixRelative(sanitizeSnapshotEntryPath(restorePath));
      if (!safePath.startsWith("uploaded-sources/files/")) continue;
      attachments.set(`${contentHash}\0${safePath}`, { content_hash: contentHash, size_bytes: size, restore_path: safePath });
    } catch {
      continue;
    }
  }
  return [...attachments.values()].sort((left, right) =>
    left.content_hash.localeCompare(right.content_hash) || left.restore_path.localeCompare(right.restore_path));
}

function normalizePublishState(value: unknown, workspaceDir: string): WorkspaceSnapshotPublishState {
  const existing = value && typeof value === "object" && !Array.isArray(value)
    ? value as Partial<WorkspaceSnapshotPublishState>
    : {};
  const base = createInitialPublishState(workspaceDir);
  const status = RUNNING_PUBLISH_STATUSES.includes(existing.status as WorkspaceSnapshotPublishStatus) ||
    existing.status === "completed" ||
    existing.status === "failed"
    ? existing.status as WorkspaceSnapshotPublishStatus
    : "idle";
  const mirror = existing.mirror && typeof existing.mirror === "object" && !Array.isArray(existing.mirror)
    ? existing.mirror as unknown as WorkspaceSnapshotMirror
    : null;
  const error = existing.error && typeof existing.error === "object" && !Array.isArray(existing.error)
    ? {
        message: typeof existing.error.message === "string" ? existing.error.message : "Snapshot publication failed",
        ...(typeof existing.error.stack === "string" ? { stack: existing.error.stack } : {}),
        ...(existing.error.interrupted === true ? { interrupted: true } : {}),
      }
    : null;
  return {
    ...base,
    status,
    job_id: typeof existing.job_id === "string" ? existing.job_id : "",
    workspace_dir: workspaceDir,
    revision: typeof existing.revision === "string" ? existing.revision : null,
    aps_path: typeof existing.aps_path === "string" ? existing.aps_path : null,
    aps_meta_path: typeof existing.aps_meta_path === "string" ? existing.aps_meta_path : null,
    meta_json: typeof existing.meta_json === "string" ? existing.meta_json : null,
    snapshot_path: typeof existing.snapshot_path === "string" ? existing.snapshot_path : null,
    source_updated_at: typeof existing.source_updated_at === "string" ? existing.source_updated_at : null,
    source_sha256: typeof existing.source_sha256 === "string" ? existing.source_sha256 : null,
    fingerprint_algo: Number.isSafeInteger(existing.fingerprint_algo) ? Number(existing.fingerprint_algo) : 1,
    snapshot_sha256: typeof existing.snapshot_sha256 === "string" ? existing.snapshot_sha256 : null,
    snapshot_size_bytes: typeof existing.snapshot_size_bytes === "number" ? existing.snapshot_size_bytes : null,
    file_count: typeof existing.file_count === "number" ? existing.file_count : 0,
    attachments: normalizeSnapshotAttachments(existing.attachments),
    lifecycle_epoch: Number.isSafeInteger(existing.lifecycle_epoch) && Number(existing.lifecycle_epoch) >= 0
      ? Number(existing.lifecycle_epoch)
      : 0,
    change_seq: Number.isSafeInteger(existing.change_seq) && Number(existing.change_seq) >= 0
      ? Number(existing.change_seq)
      : 0,
    last_synced_updated_at: typeof existing.last_synced_updated_at === "string" ? existing.last_synced_updated_at : null,
    last_synced_sha256: typeof existing.last_synced_sha256 === "string" ? existing.last_synced_sha256 : null,
    mirror,
    started_at: typeof existing.started_at === "string" ? existing.started_at : null,
    updated_at: typeof existing.updated_at === "string" ? existing.updated_at : base.updated_at,
    completed_at: typeof existing.completed_at === "string" ? existing.completed_at : null,
    error,
  };
}

function buildWorkspaceSnapshotMetaJson(input: {
  workspaceId: string;
  revision: string;
  apsPath: string;
  sourceSha256: string;
  sourceUpdatedAt: string | null;
  snapshotSha256: string;
  snapshotSizeBytes: number;
  fileCount: number;
  fingerprintAlgo: number;
  attachments: WorkspaceSnapshotAttachment[];
}): string {
  const now = new Date().toISOString();
  return JSON.stringify(
    {
      schema_version: 1,
      workspace_id: input.workspaceId,
      current_snapshot: {
        revision: input.revision,
        aps_path: input.apsPath,
        source_sha256: input.sourceSha256,
        fingerprint_algo: input.fingerprintAlgo,
        source_updated_at: input.sourceUpdatedAt,
        snapshot_sha256: input.snapshotSha256,
        size_bytes: input.snapshotSizeBytes,
        file_count: input.fileCount,
        attachment_protocol: SNAPSHOT_ATTACHMENT_PROTOCOL,
        attachments: input.attachments,
        created_at: now,
      },
      status: "synced",
      updated_at: now,
    },
    null,
    2,
  );
}

async function writeSnapshotPublishState(
  workspaceId: string,
  publish: WorkspaceSnapshotPublishState,
  options: { replace_existing_job?: boolean } = {},
): Promise<WorkspaceSnapshotPublishState> {
  const workspaceDir = path.join(WORKSPACE_ROOT, workspaceId);
  const nextPublish = normalizePublishState(publish, workspaceDir);
  return withSnapshotStateWriteLock(workspaceId, (current) => {
    const active = current.publish ? normalizePublishState(current.publish, workspaceDir) : null;
    // Plugin callbacks can arrive after a new job has replaced the old one.
    // Silently retain the current job instead of letting its stale progress or
    // failure replace the newer job contract.
    if (
      !options.replace_existing_job &&
      active?.job_id &&
      nextPublish.job_id &&
      active.job_id !== nextPublish.job_id
    ) {
      return { next: current, value: active };
    }
    return {
      next: {
        ...current,
        publish: nextPublish,
        updated_at: new Date().toISOString(),
      },
      value: nextPublish,
    };
  });
}

export interface StartWorkspaceSnapshotPublishInput {
  workspace_dir: string;
}

export interface CommitWorkspaceSnapshotPublishInput {
  workspace_dir: string;
  expected_job_id: string;
  expected_updated_at: string | null;
  expected_sha256: string;
  mirror: WorkspaceSnapshotMirror;
}

/**
 * Start (or resume) publication of the latest generated snapshot to APS. Lazily
 * recovers interrupted jobs: a publish found in a running status whose job is no
 * longer active in this process is marked failed+interrupted, then a fresh job
 * is queued. Idempotent: when the last completed publish matches the current
 * source fingerprint it returns that completed state without re-uploading.
 */
export async function startWorkspaceSnapshotPublish(
  input: StartWorkspaceSnapshotPublishInput,
): Promise<WorkspaceSnapshotPublishState> {
  const normalizedDir = normalizeSnapshotWorkspaceDir(input.workspace_dir);
  const workspaceId = path.basename(normalizedDir);
  if (await getWorkspaceTombstone(workspaceId)) {
    throw new Error("Workspace was deleted locally and is blocked from snapshot publication");
  }

  await maybePublishWorkspaceSnapshot({ workspace_dir: normalizedDir });
  return withSnapshotStateWriteLock(workspaceId, (state) => {
    if (state.status !== "completed" || !state.revision || !state.snapshot_path) {
      throw new Error(`No snapshot has been generated for workspace ${workspaceId}`);
    }

    const previous = state.publish ? normalizePublishState(state.publish, normalizedDir) : null;
    // A job already running in this process is resumed by the plugin's promise
    // tracker; interrupted-jobs recovery is the tool layer's job (it knows the
    // in-process active set), mirroring the export-artifact publish flow.
    if (previous && RUNNING_PUBLISH_STATUSES.includes(previous.status as WorkspaceSnapshotPublishStatus)) {
      return { next: state, value: previous };
    }
    if (previous?.status === "completed" && previous.last_synced_sha256 === state.source_sha256) {
      return { next: state, value: previous };
    }

    const now = new Date().toISOString();
    const apsPath = apsSnapshotPath(workspaceId, state.revision);
    const metaPath = apsMetaPath(workspaceId);
    const next = normalizePublishState(
      {
        status: "queued",
        job_id: `${workspaceId}-${state.revision}-${Date.now()}`,
        revision: state.revision,
        aps_path: apsPath,
        aps_meta_path: metaPath,
        meta_json: buildWorkspaceSnapshotMetaJson({
          workspaceId,
          revision: state.revision,
          apsPath,
          sourceSha256: state.source_sha256 ?? "",
          sourceUpdatedAt: state.source_updated_at,
          fingerprintAlgo: state.fingerprint_algo,
          snapshotSha256: state.snapshot_sha256 ?? "",
          snapshotSizeBytes: state.snapshot_size_bytes ?? 0,
          fileCount: state.file_count,
          attachments: state.attachments,
        }),
        snapshot_path: state.snapshot_path,
        source_updated_at: state.source_updated_at,
        source_sha256: state.source_sha256,
        fingerprint_algo: state.fingerprint_algo,
        snapshot_sha256: state.snapshot_sha256,
        snapshot_size_bytes: state.snapshot_size_bytes,
        file_count: state.file_count,
        attachments: state.attachments,
        lifecycle_epoch: state.lifecycle_epoch,
        change_seq: state.generated_change_seq,
        // Keep the stable baseline in the top-level state/published job until
        // this new job has committed. It must never be cleared by job creation.
        last_synced_updated_at: state.synced_baseline?.source_updated_at ?? null,
        last_synced_sha256: state.synced_baseline?.source_sha256 ?? null,
        mirror: previous?.mirror ?? null,
        started_at: now,
        updated_at: now,
        completed_at: null,
        error: null,
      },
      normalizedDir,
    );
    return {
      next: {
        ...state,
        publish: next,
        updated_at: now,
      },
      value: next,
    };
  });
}

export async function getWorkspaceSnapshotPublishStatus(input: {
  workspace_dir: string;
}): Promise<WorkspaceSnapshotPublishState> {
  const normalizedDir = normalizeSnapshotWorkspaceDir(input.workspace_dir);
  const state = await readSnapshotSyncState(path.basename(normalizedDir));
  if (!state?.publish) return createInitialPublishState(normalizedDir);
  return normalizePublishState(state.publish, normalizedDir);
}

/**
 * Persist an intermediate publish status (queued/preparing/uploading/committing
 * or a failure) while the plugin drives the upload. The final commit is written
 * by commitWorkspaceSnapshotPublish so the local state always lands last.
 */
export async function writeWorkspaceSnapshotPublish(input: {
  workspace_dir: string;
  publish: WorkspaceSnapshotPublishState;
}): Promise<WorkspaceSnapshotPublishState> {
  const normalizedDir = normalizeSnapshotWorkspaceDir(input.workspace_dir);
  const workspaceId = path.basename(normalizedDir);
  return writeSnapshotPublishState(workspaceId, normalizePublishState(input.publish, normalizedDir));
}

/**
 * Commit a completed APS upload. The ONLY place that advances the publish state
 * to completed and records last_synced_*: this write must happen after the zip
 * and meta.json are durably on APS so a crash never leaves a "synced" marker for
 * an upload that did not land.
 */
export async function commitWorkspaceSnapshotPublish(
  input: CommitWorkspaceSnapshotPublishInput,
): Promise<WorkspaceSnapshotPublishState> {
  const normalizedDir = normalizeSnapshotWorkspaceDir(input.workspace_dir);
  const workspaceId = path.basename(normalizedDir);
  if (await getWorkspaceTombstone(workspaceId)) {
    throw new Error("Workspace was deleted locally; stale snapshot publication cannot commit");
  }
  return withSnapshotStateWriteLock(workspaceId, (state) => {
    const publish = state.publish ? normalizePublishState(state.publish, normalizedDir) : null;
    if (!publish) {
      throw new Error("No snapshot publication is in progress");
    }
    if (publish.status === "completed") return { next: state, value: publish };
    if (publish.job_id !== input.expected_job_id) {
      throw new Error("Snapshot publication job changed before it committed");
    }
    // This is the upload job's immutable contract. Do not compare the live
    // top-level snapshot fields: a newer local snapshot may legitimately have
    // been generated while this job was transporting the older ZIP.
    if (publish.source_sha256 !== input.expected_sha256) {
      throw new Error("Snapshot publication source changed before it committed");
    }
    if (publish.lifecycle_epoch !== state.lifecycle_epoch) {
      throw new Error("Snapshot publication became stale because the Workspace lifecycle changed");
    }
    const now = new Date().toISOString();
    const committed: WorkspaceSnapshotPublishState = normalizePublishState(
      {
        ...publish,
        status: "completed",
        last_synced_updated_at: publish.source_updated_at,
        last_synced_sha256: publish.source_sha256,
        mirror: input.mirror,
        updated_at: now,
        completed_at: now,
        error: null,
      },
      normalizedDir,
    );
    return {
      next: {
        ...state,
        publish: committed,
        synced_baseline: {
          revision: publish.revision,
          source_updated_at: publish.source_updated_at,
          source_sha256: publish.source_sha256,
          fingerprint_algo: publish.fingerprint_algo,
          updated_at: now,
        },
        retry: state.retry?.change_seq === publish.change_seq ? null : state.retry,
        updated_at: now,
      },
      value: committed,
    };
  });
}

export async function markWorkspaceSnapshotPublishJobInterrupted(input: {
  workspace_dir: string;
}): Promise<WorkspaceSnapshotPublishState> {
  const normalizedDir = normalizeSnapshotWorkspaceDir(input.workspace_dir);
  const workspaceId = path.basename(normalizedDir);
  const state = await readSnapshotSyncState(workspaceId);
  const publish = state?.publish ? normalizePublishState(state.publish, normalizedDir) : null;
  if (!publish || !RUNNING_PUBLISH_STATUSES.includes(publish.status as WorkspaceSnapshotPublishStatus)) {
    return publish ?? createInitialPublishState(normalizedDir);
  }
  return writeSnapshotPublishState(
    workspaceId,
    normalizePublishState(
      {
        ...publish,
        status: "failed",
        updated_at: new Date().toISOString(),
        completed_at: new Date().toISOString(),
        error: {
          message: "Snapshot publication was interrupted because the engine process restarted.",
          interrupted: true,
        },
      },
      normalizedDir,
    ),
  );
}

/**
 * Rebuild the current snapshot zip from source (bypassing the fingerprint
 * idempotency check) and refresh the in-flight publish job contract so a retry
 * uploads the regenerated package. Called by the plugin when a snapshot fails
 * upload verification because the local zip file is corrupt: re-uploading the
 * same bytes can never succeed, so the zip is rebuilt first. If the source tree
 * changed meanwhile, the job is re-pointed at the new revision/aps_path/meta.
 */
export async function regenerateWorkspaceSnapshot(input: {
  workspace_dir: string;
}): Promise<WorkspaceSnapshotPublishState> {
  const normalizedDir = normalizeSnapshotWorkspaceDir(input.workspace_dir);
  const workspaceId = path.basename(normalizedDir);
  await maybePublishWorkspaceSnapshot({ workspace_dir: normalizedDir, force: true });
  const state = await readSnapshotSyncState(workspaceId);
  if (!state || state.status !== "completed" || !state.revision || !state.source_sha256 || !state.snapshot_path) {
    throw new Error(`Failed to regenerate a snapshot for workspace ${workspaceId}`);
  }
  const publish = state.publish ? normalizePublishState(state.publish, normalizedDir) : null;
  if (!publish || !publish.job_id) {
    return createInitialPublishState(normalizedDir);
  }
  const apsPath = apsSnapshotPath(workspaceId, state.revision);
  const metaPath = apsMetaPath(workspaceId);
  const refreshed: WorkspaceSnapshotPublishState = normalizePublishState(
    {
      ...publish,
      revision: state.revision,
      aps_path: apsPath,
      aps_meta_path: metaPath,
      meta_json: buildWorkspaceSnapshotMetaJson({
        workspaceId,
        revision: state.revision,
        apsPath,
        sourceSha256: state.source_sha256,
        sourceUpdatedAt: state.source_updated_at,
        fingerprintAlgo: state.fingerprint_algo,
        snapshotSha256: state.snapshot_sha256 ?? "",
        snapshotSizeBytes: state.snapshot_size_bytes ?? 0,
        fileCount: state.file_count,
        attachments: state.attachments,
      }),
      snapshot_path: state.snapshot_path,
      source_updated_at: state.source_updated_at,
      source_sha256: state.source_sha256,
      fingerprint_algo: state.fingerprint_algo,
      snapshot_sha256: state.snapshot_sha256,
      snapshot_size_bytes: state.snapshot_size_bytes,
      file_count: state.file_count,
      attachments: state.attachments,
      lifecycle_epoch: state.lifecycle_epoch,
    },
    normalizedDir,
  );
  return writeSnapshotPublishState(workspaceId, refreshed);
}

function sha256BufferHex(buffer: Buffer): string {
  return createHash("sha256").update(buffer).digest("hex");
}

// ---------------------------------------------------------------------------
// Minimal dependency-free ZIP reader. Parses snapshots we produced ourselves
// (archiver, STORE or DEFLATE entries, classic layout) so the engine can read
// and verify a snapshot without an external unzip tool. ZIP64 is not produced
// for snapshots under the 20-25 MiB ceiling and is rejected explicitly.
// ---------------------------------------------------------------------------

const EOCD_SIGNATURE = 0x06054b50;
const CENTRAL_DIRECTORY_SIGNATURE = 0x02014b50;
const LOCAL_FILE_SIGNATURE = 0x04034b50;
const ZIP64_ENTRY_COUNT_SENTINEL = 0xffff;
const ZIP64_FIELD_SENTINEL = 0xffffffff;

interface ZipCentralEntry {
  name: string;
  method: number;
  compressedSize: number;
  uncompressedSize: number;
  localHeaderOffset: number;
}

function parseZipEndOfCentralDirectory(buffer: Buffer): { entryCount: number; cdOffset: number } {
  const eocdMinimumLength = 22;
  const searchStart = Math.max(0, buffer.length - (65535 + eocdMinimumLength));
  for (let offset = buffer.length - eocdMinimumLength; offset >= searchStart; offset -= 1) {
    if (buffer.readUInt32LE(offset) !== EOCD_SIGNATURE) continue;
    const entryCount = buffer.readUInt16LE(offset + 10);
    if (entryCount === ZIP64_ENTRY_COUNT_SENTINEL) {
      throw new Error("ZIP64 archives are not supported");
    }
    const cdOffset = buffer.readUInt32LE(offset + 16);
    return { entryCount, cdOffset };
  }
  throw new Error("Not a valid ZIP archive: no End of Central Directory record found");
}

function parseZipCentralDirectory(
  buffer: Buffer,
  entryCount: number,
  cdOffset: number,
): ZipCentralEntry[] {
  const entries: ZipCentralEntry[] = [];
  let offset = cdOffset;
  for (let index = 0; index < entryCount; index += 1) {
    if (buffer.readUInt32LE(offset) !== CENTRAL_DIRECTORY_SIGNATURE) {
      throw new Error(`ZIP central directory is corrupt at entry ${index}`);
    }
    const method = buffer.readUInt16LE(offset + 10);
    const compressedSize = buffer.readUInt32LE(offset + 20);
    const uncompressedSize = buffer.readUInt32LE(offset + 24);
    const nameLength = buffer.readUInt16LE(offset + 28);
    const extraLength = buffer.readUInt16LE(offset + 30);
    const commentLength = buffer.readUInt16LE(offset + 32);
    const localHeaderOffset = buffer.readUInt32LE(offset + 42);
    if (
      compressedSize === ZIP64_FIELD_SENTINEL ||
      uncompressedSize === ZIP64_FIELD_SENTINEL ||
      localHeaderOffset === ZIP64_FIELD_SENTINEL
    ) {
      throw new Error("ZIP64 archives are not supported");
    }
    const name = buffer.subarray(offset + 46, offset + 46 + nameLength).toString("utf8");
    entries.push({ name, method, compressedSize, uncompressedSize, localHeaderOffset });
    offset += 46 + nameLength + extraLength + commentLength;
  }
  return entries;
}

function readZipEntryData(buffer: Buffer, entry: ZipCentralEntry): Buffer {
  if (buffer.readUInt32LE(entry.localHeaderOffset) !== LOCAL_FILE_SIGNATURE) {
    throw new Error(`ZIP local file header is missing for "${entry.name}"`);
  }
  const nameLength = buffer.readUInt16LE(entry.localHeaderOffset + 26);
  const extraLength = buffer.readUInt16LE(entry.localHeaderOffset + 28);
  const dataStart = entry.localHeaderOffset + 30 + nameLength + extraLength;
  const compressed = buffer.subarray(dataStart, dataStart + entry.compressedSize);
  if (entry.method === 0) return Buffer.from(compressed);
  if (entry.method === 8) return inflateRawSync(compressed);
  throw new Error(`Unsupported ZIP compression method ${entry.method} for "${entry.name}"`);
}

