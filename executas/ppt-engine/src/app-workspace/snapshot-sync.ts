/**
 * Parse a generated snapshot zip and verify its integrity: read back
 * `.snapshot-manifest.json`, recompute the sha256 of every archived file and
 * compare it with the manifest's per-file record, and cross-check the zip's own
 * sha256 against the value recorded in snapshot-sync.json at generation time.
 * Throws when the snapshot is missing or the zip is corrupt/unsupported.
 */
export async function readWorkspaceSnapshotInfo(input: {
  workspace_dir: string;
  revision?: string;
}): Promise<ReadWorkspaceSnapshotInfoResult> {
  const normalizedDir = normalizeSnapshotWorkspaceDir(input.workspace_dir);
  const workspaceId = path.basename(normalizedDir);
  const state = await readSnapshotSyncState(workspaceId);
  if (!state || state.status !== "completed" || !state.snapshot_path) {
    throw new Error(`No snapshot has been generated for workspace ${workspaceId}`);
  }
  const zipPath = input.revision
    ? path.join(snapshotFileDir(workspaceId), `${input.revision}.zip`)
    : state.snapshot_path;

  const zipBytes = await readFile(zipPath);
  const eocd = parseZipEndOfCentralDirectory(zipBytes);
  const entries = parseZipCentralDirectory(zipBytes, eocd.entryCount, eocd.cdOffset);

  const manifestEntry = entries.find((entry) => entry.name === SNAPSHOT_MANIFEST_NAME);
  if (!manifestEntry) {
    throw new Error(`Snapshot zip has no ${SNAPSHOT_MANIFEST_NAME}`);
  }
  const manifest = JSON.parse(
    readZipEntryData(zipBytes, manifestEntry).toString("utf8"),
  ) as {
    schema_version: number;
    snapshot: WorkspaceSnapshotManifestSnapshot;
  };
  if (manifest.schema_version !== SNAPSHOT_SCHEMA_VERSION) {
    throw new Error(`Snapshot schema_version ${manifest.schema_version} is not supported`);
  }
  if (manifest.snapshot?.workspace_id !== workspaceId) {
    throw new Error("Snapshot workspace_id does not match the Workspace");
  }

  const entryByName = new Map(entries.map((entry) => [entry.name, entry]));
  const tracked = new Set(manifest.snapshot.files.map((file) => file.path));
  const missingFiles: string[] = [];
  const mismatchedFiles: string[] = [];
  const verifiedEntries: WorkspaceSnapshotZipEntry[] = [];

  for (const file of manifest.snapshot.files) {
    const zipEntry = entryByName.get(file.path);
    if (!zipEntry) {
      missingFiles.push(file.path);
      continue;
    }
    const actualSha256 = sha256BufferHex(readZipEntryData(zipBytes, zipEntry));
    if (actualSha256 !== file.sha256) mismatchedFiles.push(file.path);
    verifiedEntries.push({
      name: file.path,
      method: zipEntry.method,
      compressed_size: zipEntry.compressedSize,
      uncompressed_size: zipEntry.uncompressedSize,
      sha256: actualSha256,
    });
  }
  for (const entry of entries) {
    if (tracked.has(entry.name)) continue;
    verifiedEntries.push({
      name: entry.name,
      method: entry.method,
      compressed_size: entry.compressedSize,
      uncompressed_size: entry.uncompressedSize,
      sha256: null,
    });
  }
  verifiedEntries.sort((left, right) => left.name.localeCompare(right.name));

  const zipSha256 = await sha256FileHex(zipPath);
  const zipMatchesState = state.snapshot_sha256 ? zipSha256 === state.snapshot_sha256 : null;

  return {
    workspace_id: workspaceId,
    revision: manifest.snapshot.revision,
    snapshot_path: zipPath,
    zip_sha256: zipSha256,
    zip_sha256_matches_state: zipMatchesState,
    manifest: manifest.snapshot,
    entries: verifiedEntries,
    file_count: verifiedEntries.length,
    missing_files: missingFiles,
    mismatched_files: mismatchedFiles,
    all_files_verified:
      manifest.snapshot.files.length > 0 &&
      missingFiles.length === 0 &&
      mismatchedFiles.length === 0,
  };
}

