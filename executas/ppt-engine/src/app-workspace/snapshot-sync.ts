/**
 * Relation among the live local tree (L), last confirmed sync baseline (B),
 * and APS meta.json's current snapshot (R). Content fingerprints—not mtimes—
 * are the ordering evidence. `baseline_missing` is deliberately conservative:
 * without a common ancestor, reconciliation may not overwrite local bytes.
 */
export type WorkspaceSnapshotReconcileDecision =
  | "in_sync"
  | "cloud_ahead"
  | "local_ahead"
  | "diverged"
  | "baseline_missing";

export function classifyWorkspaceSnapshotReconcile(input: {
  local_source_sha256: string | null;
  baseline_source_sha256: string | null;
  remote_source_sha256: string | null;
  local_fingerprint_algo?: number | null;
  baseline_fingerprint_algo?: number | null;
  remote_fingerprint_algo?: number | null;
}): WorkspaceSnapshotReconcileDecision {
  const local = input.local_source_sha256;
  const baseline = input.baseline_source_sha256;
  const remote = input.remote_source_sha256;
  const localAlgo = input.local_fingerprint_algo ?? SNAPSHOT_FINGERPRINT_ALGO;
  const baselineAlgo = input.baseline_fingerprint_algo ?? null;
  const remoteAlgo = input.remote_fingerprint_algo ?? null;

  if (baselineAlgo !== null && baselineAlgo !== localAlgo) return "baseline_missing";
  if (remoteAlgo !== null && remoteAlgo !== localAlgo) return "baseline_missing";

  // A matching live tree is safe regardless of whether old bookkeeping was
  // retained. A missing remote hash is never evidence that cloud is ahead.
  if (local !== null && remote !== null && local === remote) return "in_sync";
  if (baseline === null || local === null || remote === null) return "baseline_missing";
  if (local === baseline && remote !== baseline) return "cloud_ahead";
  if (remote === baseline && local !== baseline) return "local_ahead";
  return "diverged";
}

