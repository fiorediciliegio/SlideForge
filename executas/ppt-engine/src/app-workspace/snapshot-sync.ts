function stableJson(value: unknown): string {
  if (Array.isArray(value)) return `[${value.map((item) => stableJson(item)).join(",")}]`;
  if (value && typeof value === "object") {
    const record = value as Record<string, unknown>;
    return `{${Object.keys(record).sort().map((key) => `${JSON.stringify(key)}:${stableJson(record[key])}`).join(",")}}`;
  }
  return JSON.stringify(value);
}

function normalizePortablePath(value: string, workspaceDir: string): string {
  if (!path.isAbsolute(value) && !/^[A-Za-z]:[\\/]/.test(value) && !/^\\\\/.test(value)) return value;
  const normalizedWorkspace = path.resolve(workspaceDir);
  // `path.resolve` recognizes the current platform. The second branch handles
  // a Windows path stored in a snapshot being inspected on a non-Windows host.
  const normalizedValue = path.resolve(value);
  const relative = path.relative(normalizedWorkspace, normalizedValue);
  if (relative && !relative.startsWith("..") && !path.isAbsolute(relative)) {
    return `$WORKSPACE/${posixRelative(relative)}`;
  }
  const windowsMatch = /(?:^[A-Za-z]:)?[\\/].*?(ppt-\d{8}-\d{6})[\\/](.+)$/i.exec(value);
  if (windowsMatch) return `$WORKSPACE/${windowsMatch[2].replace(/[\\/]+/g, "/")}`;
  return value;
}

function normalizePortableJson(value: unknown, workspaceDir: string, key = ""): unknown {
  if (typeof value === "string") {
    // Only normalize values of explicit path-bearing fields. This avoids a
    // broad textual replacement corrupting prose, prompts, or user HTML.
    return /(?:^|_)(?:path|dir|url|source|file)(?:s)?$/i.test(key) ||
      /^(?:file:|[A-Za-z]:[\\/]|\\\\|\/)/.test(value)
      ? normalizePortablePath(value.replace(/^file:\/\//i, ""), workspaceDir)
      : value;
  }
  if (Array.isArray(value)) return value.map((item) => normalizePortableJson(item, workspaceDir, key));
  if (value && typeof value === "object") {
    return Object.fromEntries(Object.entries(value as Record<string, unknown>)
      .map(([entryKey, entryValue]) => [entryKey, normalizePortableJson(entryValue, workspaceDir, entryKey)]));
  }
  return value;
}

function normalizePortableHtml(value: string, workspaceDir: string): string {
  const escaped = workspaceDir.replace(/[.*+?^${}()|[\]\\]/g, "\\$&").replace(/[\\/]+/g, "[\\\\/]+");
  // Only file URLs / absolute attributes that point below this Workspace are
  // rewritten. Relative HTML resource references retain their original bytes.
  return value
    .replace(new RegExp(`file:(?:\\/\\/)?${escaped}([\\\\/][^'"\\s<>]*)`, "gi"), (_match, suffix) =>
      `file:///$WORKSPACE/${String(suffix).replace(/^[\\/]+/, "").replace(/[\\/]+/g, "/")}`)
    .replace(new RegExp(`(["'])${escaped}([\\\\/][^"']*)\\1`, "gi"), (_match, quote, suffix) =>
      `${quote}$WORKSPACE/${String(suffix).replace(/^[\\/]+/, "").replace(/[\\/]+/g, "/")}${quote}`);
}

