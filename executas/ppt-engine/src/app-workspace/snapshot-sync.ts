function sameStringSet(left: Set<string>, right: Set<string>): boolean {
  if (left.size !== right.size) return false;
  for (const value of left) {
    if (!right.has(value)) return false;
  }
  return true;
}

function readSnapshotJsonEntry(
  zipBytes: Buffer,
  entryByName: Map<string, ZipCentralEntry>,
  entryName: string,
  errors: WorkspaceSnapshotSemanticError[],
  required = true,
): Record<string, unknown> | null {
  const entry = entryByName.get(entryName);
  if (!entry) {
    if (required) {
      errors.push({
        code: "snapshot_json_missing",
        message: `Snapshot has no required ${entryName}`,
        paths: [entryName],
      });
    }
    return null;
  }
  try {
    const record = asRecord(JSON.parse(readZipEntryData(zipBytes, entry).toString("utf8")));
    if (record) return record;
  } catch {
    // Record the stable validation error below rather than leaking a parser-specific message.
  }
  errors.push({
    code: "snapshot_json_invalid",
    message: `Snapshot ${entryName} is not a JSON object`,
    paths: [entryName],
  });
  return null;
}

/**
 * Validates relationships among the authoritative files in one already-built
 * snapshot ZIP. This deliberately reads the archive rather than the live
 * Workspace so the exact bytes eligible for APS publication are validated.
 */
export async function validateWorkspaceSnapshotZipSemantics(input: {
  zip_path: string;
}): Promise<WorkspaceSnapshotSemanticValidationResult> {
  const zipBytes = await readFile(input.zip_path);
  const errors: WorkspaceSnapshotSemanticError[] = [];
  let entries: ZipCentralEntry[];
  try {
    const eocd = parseZipEndOfCentralDirectory(zipBytes);
    entries = parseZipCentralDirectory(zipBytes, eocd.entryCount, eocd.cdOffset);
  } catch {
    return {
      ok: false,
      errors: [{
        code: "snapshot_zip_invalid",
        message: "Snapshot ZIP cannot be read for semantic validation",
        paths: [],
      }],
    };
  }

  const entryByName = new Map(entries.map((entry) => [entry.name, entry]));
  const outline = readSnapshotJsonEntry(zipBytes, entryByName, "outline.json", errors);
  const pageProgress = readSnapshotJsonEntry(zipBytes, entryByName, "page-progress.json", errors);
  const manifest = readSnapshotJsonEntry(zipBytes, entryByName, "manifest.json", errors, false);
  if (!outline || !pageProgress || (entryByName.has("manifest.json") && !manifest)) {
    return { ok: false, errors };
  }

  const outlineStatus = outline.status;
  const outlineItems = Array.isArray(outline.items) ? outline.items : null;
  if (outlineStatus !== "empty" && outlineStatus !== "draft" && outlineStatus !== "confirmed") {
    errors.push({
      code: "outline_status_invalid",
      message: "Outline status must be empty, draft, or confirmed",
      paths: ["outline.json"],
    });
  }
  if (!outlineItems) {
    errors.push({
      code: "outline_items_invalid",
      message: "Outline items must be an array",
      paths: ["outline.json"],
    });
  } else if (outlineStatus === "empty" && outlineItems.length > 0) {
    errors.push({
      code: "outline_empty_with_items",
      message: "An empty outline cannot contain page items",
      paths: ["outline.json"],
    });
  } else if ((outlineStatus === "draft" || outlineStatus === "confirmed") && outlineItems.length === 0) {
    errors.push({
      code: "outline_nonempty_without_items",
      message: "A draft or confirmed outline requires page items",
      paths: ["outline.json"],
    });
  }

  const archivedSlideIds = new Set(
    entries
      .map((entry) => /^slides\/([^/]+)\.html$/u.exec(entry.name)?.[1] ?? null)
      .filter((pageId): pageId is string => pageId !== null),
  );
  if (!manifest) {
    if (archivedSlideIds.size > 0) {
      errors.push({
        code: "slides_without_manifest",
        message: "Archived slide HTML requires manifest.json entries",
        paths: ["manifest.json", ...[...archivedSlideIds].sort().map((pageId) => `slides/${pageId}.html`)],
      });
    }
    if (pageProgress.status === "completed") {
      errors.push({
        code: "completed_progress_without_manifest_pages",
        message: "Completed page progress requires manifest pages",
        paths: ["page-progress.json", "manifest.json"],
      });
    }
    return { ok: errors.length === 0, errors };
  }

  if (!Array.isArray(manifest.slides)) {
    errors.push({
      code: "manifest_slides_invalid",
      message: "Manifest slides must be an array",
      paths: ["manifest.json"],
    });
    return { ok: false, errors };
  }
  const slides = manifest.slides;
  const manifestIds = new Set<string>();
  const duplicateManifestIds = new Set<string>();
  for (const slide of slides) {
    const record = asRecord(slide);
    const id = typeof record?.id === "string" ? record.id.trim() : "";
    if (!id) {
      errors.push({
        code: "manifest_slide_id_invalid",
        message: "Manifest contains a slide without a valid id",
        paths: ["manifest.json"],
      });
      continue;
    }
    if (manifestIds.has(id)) duplicateManifestIds.add(id);
    manifestIds.add(id);
  }
  if (duplicateManifestIds.size > 0) {
    errors.push({
      code: "manifest_slide_ids_duplicate",
      message: "Manifest contains duplicate slide ids",
      paths: [...duplicateManifestIds].sort().map((id) => `manifest.json#${id}`),
    });
  }

  // A completed Deck can legitimately coexist with a later Outline Draft:
  // saving a post-generation outline edit deliberately removes page_id values
  // until that draft is confirmed for the next full generation. Page identity
  // cross-checks are therefore meaningful only for a Confirmed Outline. The
  // manifest/archive and page-progress checks below remain unconditional: they
  // validate the existing Deck independently of the next outline lifecycle.
  if (manifestIds.size > 0 && outline.status === "confirmed") {
    if (!outlineItems || outlineItems.length === 0) {
      errors.push({
        code: "outline_missing_items_for_pages",
        message: "A snapshot with manifest pages requires non-empty outline items",
        paths: ["outline.json", "manifest.json"],
      });
    }
    const outlineIds = new Set<string>();
    const duplicateOutlineIds = new Set<string>();
    for (const item of outlineItems ?? []) {
      const record = asRecord(item);
      const pageId = typeof record?.page_id === "string" ? record.page_id.trim() : "";
      if (!pageId) {
        errors.push({
          code: "outline_page_id_invalid",
          message: "Confirmed outline contains an item without a valid page_id",
          paths: ["outline.json"],
        });
        continue;
      }
      if (outlineIds.has(pageId)) duplicateOutlineIds.add(pageId);
      outlineIds.add(pageId);
    }
    if (duplicateOutlineIds.size > 0) {
      errors.push({
        code: "outline_page_ids_duplicate",
        message: "Confirmed outline contains duplicate page_id values",
        paths: [...duplicateOutlineIds].sort().map((id) => `outline.json#${id}`),
      });
    }
    if (!sameStringSet(outlineIds, manifestIds)) {
      errors.push({
        code: "outline_manifest_page_ids_mismatch",
        message: "Confirmed outline and manifest do not describe the same page ids",
        paths: ["outline.json", "manifest.json"],
      });
    }
    for (const pageId of manifestIds) {
      const sourcePath = `slides/${pageId}.html`;
      if (!entryByName.has(sourcePath)) {
        errors.push({
          code: "manifest_slide_source_missing",
          message: `Manifest page ${pageId} has no archived ${sourcePath}`,
          paths: ["manifest.json", sourcePath],
        });
      }
    }
  }

  if (!sameStringSet(archivedSlideIds, manifestIds)) {
    errors.push({
      code: "manifest_archive_slide_ids_mismatch",
      message: "Manifest and archived slide HTML do not describe the same page ids",
      paths: [
        "manifest.json",
        ...[...archivedSlideIds].sort().map((pageId) => `slides/${pageId}.html`),
      ],
    });
  }

  if (pageProgress.status === "completed") {
    if (manifestIds.size === 0) {
      errors.push({
        code: "completed_progress_without_manifest_pages",
        message: "Completed page progress requires manifest pages",
        paths: ["page-progress.json", "manifest.json"],
      });
    }
    const progressItems = Array.isArray(pageProgress.pages) ? pageProgress.pages : null;
    if (!progressItems) {
      errors.push({
        code: "completed_progress_pages_invalid",
        message: "Completed page progress requires a pages array",
        paths: ["page-progress.json"],
      });
    } else {
      const progressIds = new Set<string>();
      let hasInvalidProgressId = false;
      for (const item of progressItems) {
        const record = asRecord(item);
        const pageId = typeof record?.page_id === "string" ? record.page_id.trim() : "";
        if (!pageId) {
          hasInvalidProgressId = true;
          continue;
        }
        progressIds.add(pageId);
      }
      if (hasInvalidProgressId) {
        errors.push({
          code: "completed_progress_pages_invalid",
          message: "Completed page progress contains a page without a valid page_id",
          paths: ["page-progress.json"],
        });
      }
      if (!sameStringSet(progressIds, manifestIds)) {
        errors.push({
          code: "completed_progress_page_ids_mismatch",
          message: "Completed page progress and manifest do not describe the same page ids",
          paths: ["page-progress.json", "manifest.json"],
        });
      }
    }
  }

  return { ok: errors.length === 0, errors };
}

