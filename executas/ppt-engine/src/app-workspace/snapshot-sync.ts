function isNotFoundError(error: unknown): boolean {
  return Boolean(
    error &&
      typeof error === "object" &&
      "code" in error &&
      error.code === "ENOENT",
  );
}

function sha256Hex(value: string): string {
  return createHash("sha256").update(value).digest("hex");
}

async function sha256FileHex(filePath: string): Promise<string> {
  return new Promise((resolve, reject) => {
    const hash = createHash("sha256");
    const stream = createReadStream(filePath);
    stream.on("data", (chunk) => hash.update(chunk));
    stream.on("error", reject);
    stream.on("end", () => resolve(hash.digest("hex")));
  });
}

// Returns the digest a file contributes to the conflict fingerprint. task.json's
// updated_at bumps on every open, so it is stripped before hashing; the result
// is normalized (parse + re-stringify) so key ordering/whitespace never leaks
// into the fingerprint. All other files hash by raw bytes.
async function fingerprintFileSha256(file: SnapshotSourceFile, workspaceDir: string): Promise<string> {
  try {
    const raw = await readFile(file.absolutePath, "utf8");
    if (file.relativePath.endsWith(".json")) {
      const value: unknown = JSON.parse(raw);
      if (!value || typeof value !== "object") return sha256FileHex(file.absolutePath);
      const record = value as Record<string, unknown>;
      if (file.relativePath === "task.json") delete record.updated_at;
      return sha256Hex(stableJson(normalizePortableJson(record, workspaceDir)));
    }
    if (file.relativePath.endsWith(".html") || file.relativePath.endsWith(".htm")) {
      return sha256Hex(normalizePortableHtml(raw, workspaceDir));
    }
    return sha256FileHex(file.absolutePath);
  } catch {
    return sha256FileHex(file.absolutePath);
  }
}

async function readJsonFileIfExists(filePath: string): Promise<unknown | null> {
  try {
    return JSON.parse(await readFile(filePath, "utf8")) as unknown;
  } catch (error) {
    if (isNotFoundError(error)) return null;
    return null;
  }
}

async function atomicWriteJsonFile(filePath: string, data: unknown): Promise<void> {
  await mkdir(path.dirname(filePath), { recursive: true });
  // A unique temp name avoids same-process collisions (concurrent writers to
  // the same state file); retrying handles transient Windows locks (antivirus
  // scans, brief handles) that make the atomic rename throw EPERM.
  const temporaryPath = path.join(
    path.dirname(filePath),
    `.${path.basename(filePath)}.${process.pid}.${randomBytes(4).toString("hex")}.tmp`,
  );
  const body = `${JSON.stringify(data, null, 2)}\n`;
  for (let attempt = 1; ; attempt += 1) {
    try {
      await writeFile(temporaryPath, body, "utf8");
      await rename(temporaryPath, filePath);
      return;
    } catch (error) {
      await unlink(temporaryPath).catch(() => undefined);
      if (attempt >= 5) throw error;
      const code = (error as NodeJS.ErrnoException)?.code;
      if (code !== "EPERM" && code !== "EBUSY" && code !== "EACCES") throw error;
      await new Promise((resolve) => setTimeout(resolve, 100 * attempt));
    }
  }
}

function normalizeSnapshotWorkspaceDir(workspaceDir: string): string {
  if (!workspaceDir || typeof workspaceDir !== "string") {
    throw new Error('"workspace_dir" must be a non-empty string');
  }
  if (!path.isAbsolute(workspaceDir)) {
    throw new Error('"workspace_dir" must be an absolute path');
  }
  const normalized = path.normalize(workspaceDir);
  if (!WORKSPACE_DIR_PATTERN.test(path.basename(normalized))) {
    throw new Error('"workspace_dir" must point to a ppt-YYYYMMDD-HHmmss directory');
  }
  const relative = path.relative(WORKSPACE_ROOT, normalized);
  if (relative.length === 0 || relative.startsWith("..") || path.isAbsolute(relative)) {
    throw new Error('"workspace_dir" must be under the default PPT workspace root');
  }
  return normalized;
}

async function collectSnapshotSources(workspaceDir: string): Promise<SnapshotSourceFile[]> {
  const files: SnapshotSourceFile[] = [];
  const seen = new Set<string>();

  async function addFile(absolutePath: string, relativePath: string): Promise<void> {
    const info = await lstat(absolutePath);
    const relative = posixRelative(relativePath);
    if (/^manual-edits\/[^/]+\/current\.png$/.test(relative)) return;
    if (info.isSymbolicLink()) {
      throw new Error(`Snapshot cannot include symbolic link: ${relative}`);
    }
    if (!info.isFile()) {
      throw new Error(`Snapshot expected a file but found a directory: ${relative}`);
    }
    if (seen.has(relative)) return;
    seen.add(relative);
    files.push({
      relativePath: relative,
      absolutePath,
      size: info.size,
      mtimeMs: info.mtimeMs,
      ino: info.ino,
      mode: info.mode,
    });
  }

  // Orphan slide guard: when a page id set is replaced (regeneration/replan),
  // the old slides/<id>.html can be left on disk. The semantic validation below
  // requires the archived slide set to equal the manifest slide set, so an
  // orphan would fail every snapshot build and permanently block cloud publish
  // (snapshotNeedsUpload refuses states with semantic_validation_failed).
  // Excluding undeclared slides from the snapshot keeps validation honest while
  // the on-disk prune happens at the manifest-write sites.
  let declaredSlideIds: Set<string> | null = null;
  try {
    const manifestRaw = await readFile(path.join(workspaceDir, "manifest.json"), "utf8");
    const manifestRecord = JSON.parse(manifestRaw) as { slides?: unknown };
    if (Array.isArray(manifestRecord.slides)) {
      declaredSlideIds = new Set<string>();
      for (const slide of manifestRecord.slides) {
        const record = slide as { id?: unknown };
        if (typeof record?.id === "string" && record.id.trim()) declaredSlideIds.add(record.id.trim());
      }
    }
  } catch (error) {
    if (!isNotFoundError(error)) throw error;
  }

  async function walkDirectory(
    directoryPath: string,
    relativeDirectory: string,
    includeFile?: (relativePath: string) => boolean,
  ): Promise<void> {
    const entries = await readdir(directoryPath, { withFileTypes: true });
    entries.sort((left, right) => left.name.localeCompare(right.name));
    for (const entry of entries) {
      const absolutePath = path.join(directoryPath, entry.name);
      const relativePath = relativeDirectory
        ? path.join(relativeDirectory, entry.name)
        : entry.name;
      const info = await lstat(absolutePath);
      if (info.isDirectory()) {
        await walkDirectory(absolutePath, relativePath, includeFile);
        continue;
      }
      if (info.isFile()) {
        if (includeFile && !includeFile(relativePath)) continue;
        await addFile(absolutePath, relativePath);
        continue;
      }
      if (info.isSymbolicLink()) {
        throw new Error(`Snapshot cannot include symbolic link: ${posixRelative(relativePath)}`);
      }
      throw new Error(`Snapshot cannot include special file: ${posixRelative(relativePath)}`);
    }
  }

  for (const name of SNAPSHOT_FILE_WHITELIST) {
    try {
      await addFile(path.join(workspaceDir, name), name);
    } catch (error) {
      if (!isNotFoundError(error)) throw error;
    }
  }

  for (const name of SNAPSHOT_DIR_WHITELIST) {
    const absolutePath = path.join(workspaceDir, name);
    try {
      const info = await lstat(absolutePath);
      if (info.isDirectory()) {
        await walkDirectory(
          absolutePath,
          name,
          name === "slides" && declaredSlideIds
            ? (relativePath) => {
                const id = path.basename(relativePath, ".html");
                return declaredSlideIds.has(id);
              }
            : undefined,
        );
      }
    } catch (error) {
      if (!isNotFoundError(error)) throw error;
    }
  }

  // Apart from the authored asset copies above, uploaded-sources contributes
  // only its reference index; original attachment bodies
  // (files/) are uploaded to APS separately by content hash in the later
  // increment, so they never enter the snapshot.
  try {
    await addFile(
      path.join(workspaceDir, "uploaded-sources", "index.json"),
      path.join("uploaded-sources", "index.json"),
    );
  } catch (error) {
    if (!isNotFoundError(error)) throw error;
  }
  try {
    await addFile(
      path.join(workspaceDir, "uploaded-sources", "attachment-context.json"),
      path.join("uploaded-sources", "attachment-context.json"),
    );
  } catch (error) {
    if (!isNotFoundError(error)) throw error;
  }

  files.sort((left, right) => left.relativePath.localeCompare(right.relativePath));
  return files;
}

async function computeSnapshotFingerprint(files: SnapshotSourceFile[], workspaceDir: string): Promise<SnapshotFingerprint> {
  const fileDigests: { path: string; sha256: string; size: number }[] = [];
  const fingerprintEntries: { path: string; sha256: string }[] = [];
  let maxMtimeMs = 0;
  for (const file of files) {
    const sha256 = await sha256FileHex(file.absolutePath);
    fileDigests.push({ path: file.relativePath, sha256, size: file.size });
    // fileDigests stays raw for zip integrity; the conflict fingerprint hashes
    // only non-reconstructible, normalized content so freshly-restored
    // workspaces don't false-conflict after local regeneration.
    if (SNAPSHOT_FINGERPRINT_EXCLUDED_PATHS.has(file.relativePath)) continue;
    fingerprintEntries.push({ path: file.relativePath, sha256: await fingerprintFileSha256(file, workspaceDir) });
    if (file.mtimeMs > maxMtimeMs) maxMtimeMs = file.mtimeMs;
  }
  const canonical = fingerprintEntries
    .map((digest) => `${digest.path}\0${digest.sha256}\n`)
    .join("");
  const sourceSha256 = sha256Hex(canonical);
  const sourceUpdatedAt = maxMtimeMs > 0 ? new Date(maxMtimeMs).toISOString() : null;
  const revision = maxMtimeMs > 0 ? String(Math.floor(maxMtimeMs)) : null;
  return { sourceSha256, sourceUpdatedAt, revision, fileDigests };
}

async function collectSnapshotAttachmentHashes(
  workspaceDir: string,
): Promise<WorkspaceSnapshotAttachment[]> {
  const indexPath = path.join(workspaceDir, "uploaded-sources", "index.json");
  const value = await readJsonFileIfExists(indexPath);
  if (!value || typeof value !== "object" || Array.isArray(value)) return [];
  const materials = (value as Record<string, unknown>).materials;
  if (!Array.isArray(materials)) return [];
  const attachments = new Map<string, WorkspaceSnapshotAttachment>();
  for (const item of materials) {
    if (!item || typeof item !== "object" || Array.isArray(item)) continue;
    const record = item as Record<string, unknown>;
    if (record.status !== "active") continue;
    const contentHash = typeof record.sha256 === "string" ? record.sha256.toLowerCase() : "";
    const filePath = typeof record.file_path === "string" ? record.file_path : "";
    if (!/^[a-f0-9]{64}$/.test(contentHash) || !filePath) {
      throw new Error("Active uploaded source is missing its attachment SHA-256 or file path");
    }
    const relative = path.relative(workspaceDir, filePath);
    if (!relative || relative.startsWith("..") || path.isAbsolute(relative) || !posixRelative(relative).startsWith("uploaded-sources/files/")) {
      throw new Error(`Active uploaded source file must be under uploaded-sources/files: ${filePath}`);
    }
    const info = await stat(filePath);
    if (!info.isFile()) throw new Error(`Active uploaded source attachment is missing: ${filePath}`);
    const actualHash = await sha256FileHex(filePath);
    if (actualHash !== contentHash) throw new Error(`Active uploaded source attachment hash changed: ${filePath}`);
    const attachment: WorkspaceSnapshotAttachment = {
      content_hash: contentHash,
      size_bytes: info.size,
      restore_path: posixRelative(relative),
    };
    attachments.set(`${contentHash}\0${attachment.restore_path}`, attachment);
  }
  return [...attachments.values()].sort((left, right) =>
    left.content_hash.localeCompare(right.content_hash) || left.restore_path.localeCompare(right.restore_path));
}

async function verifySnapshotEntry(snapshot: SnapshotEntrySnapshot): Promise<void> {
  let current;
  try {
    current = await lstat(snapshot.absolutePath);
  } catch {
    throw new Error(`Snapshot source disappeared while building: ${snapshot.relativePath}`);
  }
  if (
    !current.isFile() ||
    current.size !== snapshot.size ||
    current.mtimeMs !== snapshot.mtimeMs ||
    current.ino !== snapshot.ino
  ) {
    throw new Error(`Snapshot source changed while building: ${snapshot.relativePath}`);
  }
}

async function buildSnapshotZip(input: {
  workspaceId: string;
  files: SnapshotSourceFile[];
  fileDigests: { path: string; sha256: string; size: number }[];
  sourceSha256: string;
  sourceUpdatedAt: string | null;
  revision: string;
  attachments: WorkspaceSnapshotAttachment[];
}): Promise<{ zipPath: string; sizeBytes: number; zipSha256: string }> {
  const archiveDir = snapshotFileDir(input.workspaceId);
  await mkdir(archiveDir, { recursive: true });
  // Keep this archive private until its bytes have passed both the per-file
  // integrity checks below and the cross-file semantic checks in the caller.
  // In particular, never write an unvalidated candidate over the previous
  // known-good revision.
  const zipPath = path.join(
    archiveDir,
    `.${input.revision}.${process.pid}.${randomBytes(4).toString("hex")}.candidate.zip`,
  );
  const manifest = {
    schema_version: SNAPSHOT_SCHEMA_VERSION,
    snapshot: {
      workspace_id: input.workspaceId,
      revision: input.revision,
      source_sha256: input.sourceSha256,
      fingerprint_algo: SNAPSHOT_FINGERPRINT_ALGO,
      source_updated_at: input.sourceUpdatedAt,
      files: input.fileDigests.map((digest) => ({
        path: digest.path,
        sha256: digest.sha256,
        size: digest.size,
      })),
      attachments: input.attachments,
      attachment_protocol: SNAPSHOT_ATTACHMENT_PROTOCOL,
      created_at: new Date().toISOString(),
    },
  };

  const output = createWriteStream(zipPath, { flags: "w" });
  const archive = new ZipArchive({ zlib: { level: 6 } });
  const entriesByName = new Map<string, SnapshotEntrySnapshot>();
  for (const file of input.files) {
    entriesByName.set(file.relativePath, file);
  }
  const verificationChecks: Promise<void>[] = [];
  let verificationError: unknown = null;
  archive.on("warning", (error: ArchiverError) => archive.destroy(error));
  archive.on("entry", (entry) => {
    const snapshot = entriesByName.get(entry.name);
    if (!snapshot) return;
    verificationChecks.push(
      verifySnapshotEntry(snapshot).catch((error) => {
        verificationError ??= error;
      }),
    );
  });
  const completed = pipeline(archive, output);

  try {
    archive.append(Buffer.from(`${JSON.stringify(manifest, null, 2)}\n`, "utf8"), {
      name: SNAPSHOT_MANIFEST_NAME,
      type: "file",
    });
    for (const file of input.files) {
      const info = await lstat(file.absolutePath);
      archive.file(file.absolutePath, {
        name: file.relativePath,
        date: new Date(info.mtime),
        mode: info.mode,
        stats: info,
      });
    }
    await archive.finalize();
    await completed;
    await Promise.all(verificationChecks);
    if (verificationError) throw verificationError;
    const archiveInfo = await stat(zipPath);
    if (!archiveInfo.isFile() || archiveInfo.size <= 0) {
      throw new Error("Snapshot zip is empty");
    }
    const zipSha256 = await sha256FileHex(zipPath);
    return { zipPath, sizeBytes: archiveInfo.size, zipSha256 };
  } catch (error) {
    archive.abort();
    output.destroy();
    await completed.catch(() => undefined);
    await unlink(zipPath).catch(() => undefined);
    throw error;
  }
}

function nextSnapshotRevision(
  fingerprintRevision: string,
  existingRevision: string | null | undefined,
): string {
  const sourceRevision = Number(fingerprintRevision);
  const previousRevision = Number(existingRevision);
  if (!Number.isSafeInteger(sourceRevision) || sourceRevision < 0) {
    throw new Error(`Invalid snapshot revision: ${fingerprintRevision}`);
  }
  if (!Number.isSafeInteger(previousRevision) || previousRevision < 0) {
    return String(sourceRevision);
  }
  // mtime is normally monotonic, but Windows permits multiple writes in one
  // timestamp tick and a restored workspace can carry an older mtime. A
  // strictly increasing revision prevents either case from replacing an older
  // snapshot before the new candidate is validated.
  return String(Math.max(sourceRevision, previousRevision + 1));
}

function createInitialSnapshotSyncState(workspaceId: string): WorkspaceSnapshotSyncState {
  const now = new Date().toISOString();
  return {
    schema_version: 1,
    workspace_id: workspaceId,
    status: "idle",
    revision: null,
    source_updated_at: null,
    source_sha256: null,
    fingerprint_algo: SNAPSHOT_FINGERPRINT_ALGO,
    snapshot_sha256: null,
    snapshot_path: null,
    snapshot_size_bytes: null,
    file_count: 0,
    attachments: [],
    lifecycle_epoch: 0,
    generated_at: null,
    created_at: now,
    updated_at: now,
    error: null,
    synced_baseline: null,
    change_seq: 0,
    pending_change_seq: null,
    generated_change_seq: 0,
    retry: null,
    semantic_validation_failed: null,
    publish: null,
    restore: null,
    rebuild: null,
  };
}

async function readSnapshotSyncState(workspaceId: string): Promise<WorkspaceSnapshotSyncState | null> {
  const value = await readJsonFileIfExists(snapshotStatePath(workspaceId));
  if (!value || typeof value !== "object" || Array.isArray(value)) return null;
  const record = value as Record<string, unknown>;
  if (record.schema_version !== SNAPSHOT_SCHEMA_VERSION) return null;
  if (typeof record.workspace_id !== "string" || record.workspace_id !== workspaceId) return null;
  const base = createInitialSnapshotSyncState(workspaceId);
  const publish = record.publish && typeof record.publish === "object" && !Array.isArray(record.publish)
    ? normalizePublishState(record.publish, path.join(WORKSPACE_ROOT, workspaceId))
    : null;
  const storedBaseline = record.synced_baseline && typeof record.synced_baseline === "object" && !Array.isArray(record.synced_baseline)
    ? record.synced_baseline as Partial<WorkspaceSnapshotSyncedBaseline>
    : null;
  // schema_version remains 1: old states carry the same information under the
  // completed publish job. Read it as a baseline immediately, and the next
  // state write persists the normalized top-level representation.
  const migratedSourceSha256 = typeof publish?.last_synced_sha256 === "string" && publish.last_synced_sha256
    ? publish.last_synced_sha256
    : null;
  const sourceSha256 = typeof storedBaseline?.source_sha256 === "string" && storedBaseline.source_sha256
    ? storedBaseline.source_sha256
    : migratedSourceSha256;
  const syncedBaseline = sourceSha256
    ? {
        revision: typeof storedBaseline?.revision === "string"
          ? storedBaseline.revision
          : (publish?.revision ?? null),
        source_updated_at: typeof storedBaseline?.source_updated_at === "string"
          ? storedBaseline.source_updated_at
          : (publish?.last_synced_updated_at ?? null),
        source_sha256: sourceSha256,
        fingerprint_algo: Number.isSafeInteger(storedBaseline?.fingerprint_algo)
          ? Number(storedBaseline?.fingerprint_algo)
          : 1,
        updated_at: typeof storedBaseline?.updated_at === "string"
          ? storedBaseline.updated_at
          : (publish?.completed_at ?? publish?.updated_at ?? base.updated_at),
      }
    : null;
  const changeSeq = Number.isSafeInteger(record.change_seq) && Number(record.change_seq) >= 0
    ? Number(record.change_seq)
    : 0;
  const generatedChangeSeq = Number.isSafeInteger(record.generated_change_seq) && Number(record.generated_change_seq) >= 0
    ? Number(record.generated_change_seq)
    // Legacy completed snapshots predate change_seq. Treat them as covering
    // the best sequence we know rather than creating a false retry budget.
    : (typeof record.source_sha256 === "string" && record.source_sha256 ? changeSeq : 0);
  const rawRetry = record.retry && typeof record.retry === "object" && !Array.isArray(record.retry)
    ? record.retry as Partial<WorkspaceSnapshotRetryState>
    : null;
  const retry = rawRetry && Number.isSafeInteger(rawRetry.change_seq) && Number(rawRetry.change_seq) >= 0
    && Number.isSafeInteger(rawRetry.attempts) && Number(rawRetry.attempts) >= 0
    ? {
        change_seq: Number(rawRetry.change_seq),
        attempts: Number(rawRetry.attempts),
        phase: rawRetry.phase === "generation" || rawRetry.phase === "semantic_validation" || rawRetry.phase === "upload"
          ? rawRetry.phase
          : null,
        next_retry_at: typeof rawRetry.next_retry_at === "string" ? rawRetry.next_retry_at : null,
        exhausted: rawRetry.exhausted === true,
        last_error: typeof rawRetry.last_error === "string" ? rawRetry.last_error : null,
        updated_at: typeof rawRetry.updated_at === "string" ? rawRetry.updated_at : base.updated_at,
      } satisfies WorkspaceSnapshotRetryState
    : null;
  const rawSemanticFailure = record.semantic_validation_failed
    && typeof record.semantic_validation_failed === "object"
    && !Array.isArray(record.semantic_validation_failed)
    ? record.semantic_validation_failed as Partial<WorkspaceSnapshotSemanticValidationFailure>
    : null;
  // A state written before failure ownership existed is retained as sequence
  // zero. The next authoritative mutation invalidates it; do not guess that a
  // current local tree was the failed candidate.
  const semanticValidationFailure = rawSemanticFailure
    && typeof rawSemanticFailure.source_sha256 === "string"
    && typeof rawSemanticFailure.revision === "string"
    && Array.isArray(rawSemanticFailure.errors)
    ? {
        change_seq: Number.isSafeInteger(rawSemanticFailure.change_seq) && Number(rawSemanticFailure.change_seq) >= 0
          ? Number(rawSemanticFailure.change_seq)
          : 0,
        source_sha256: rawSemanticFailure.source_sha256,
        source_updated_at: typeof rawSemanticFailure.source_updated_at === "string"
          ? rawSemanticFailure.source_updated_at
          : null,
        revision: rawSemanticFailure.revision,
        failed_at: typeof rawSemanticFailure.failed_at === "string"
          ? rawSemanticFailure.failed_at
          : base.updated_at,
        errors: rawSemanticFailure.errors as WorkspaceSnapshotSemanticError[],
      } satisfies WorkspaceSnapshotSemanticValidationFailure
    : null;
  return {
    ...base,
    ...record,
    publish,
    restore: record.restore ?? null,
    rebuild: record.rebuild ?? null,
    synced_baseline: syncedBaseline,
    change_seq: changeSeq,
    pending_change_seq: Number.isSafeInteger(record.pending_change_seq) && Number(record.pending_change_seq) >= 0
      ? Number(record.pending_change_seq)
      : null,
    generated_change_seq: generatedChangeSeq,
    fingerprint_algo: Number.isSafeInteger(record.fingerprint_algo) ? Number(record.fingerprint_algo) : 1,
    lifecycle_epoch: Number.isSafeInteger(record.lifecycle_epoch) && Number(record.lifecycle_epoch) >= 0
      ? Number(record.lifecycle_epoch)
      : 0,
    retry,
    semantic_validation_failed: semanticValidationFailure,
  } as WorkspaceSnapshotSyncState;
}

// Every mutation of snapshot-sync.json for one Workspace passes through this
// queue. atomicWriteJsonFile prevents torn files; this lock additionally
// prevents a writer that read an older state from replacing fields another
// state machine has just committed.
const workspaceSnapshotStateWriteQueues = new Map<string, Promise<unknown>>();

async function withSnapshotStateWriteLock<T>(
  workspaceId: string,
  mutate: (current: WorkspaceSnapshotSyncState) => Promise<{
    next: WorkspaceSnapshotSyncState;
    value: T;
  }> | {
    next: WorkspaceSnapshotSyncState;
    value: T;
  },
): Promise<T> {
  const previous = workspaceSnapshotStateWriteQueues.get(workspaceId) ?? Promise.resolve();
  const current = previous
    .catch(() => undefined)
    .then(async () => {
      const latest = await readSnapshotSyncState(workspaceId) ?? createInitialSnapshotSyncState(workspaceId);
      const { next, value } = await mutate(latest);
      await atomicWriteJsonFile(snapshotStatePath(workspaceId), next);
      return value;
    });
  workspaceSnapshotStateWriteQueues.set(workspaceId, current);
  try {
    return await current;
  } finally {
    if (workspaceSnapshotStateWriteQueues.get(workspaceId) === current) {
      workspaceSnapshotStateWriteQueues.delete(workspaceId);
    }
  }
}

const workspaceSnapshotQueues = new Map<string, Promise<unknown>>();

const SNAPSHOT_RETRY_DELAYS_MS = [2_000, 5_000, 15_000] as const;

function settleSnapshotRetry(
  retry: WorkspaceSnapshotRetryState | null,
  changeSeq: number,
): WorkspaceSnapshotRetryState | null {
  if (!retry || retry.change_seq !== changeSeq) return retry;
  return {
    ...retry,
    phase: null,
    next_retry_at: null,
    exhausted: false,
    last_error: null,
    updated_at: new Date().toISOString(),
  };
}

export interface RecordWorkspaceSnapshotRetryInput {
  workspace_dir: string;
  phase: WorkspaceSnapshotRetryPhase;
  error: string;
}

/**
 * Spend one durable retry attempt for the current unsynchronized change. New
 * edits reset this record in markWorkspaceSnapshotDirty; process restarts do
 * not. The plugin uses next_retry_at to avoid hot-looping a broken candidate.
 */
export async function recordWorkspaceSnapshotRetry(
  input: RecordWorkspaceSnapshotRetryInput,
): Promise<WorkspaceSnapshotRetryState> {
  const workspaceDir = normalizeSnapshotWorkspaceDir(input.workspace_dir);
  const workspaceId = path.basename(workspaceDir);
  return withSnapshotStateWriteLock(workspaceId, (current) => {
    const changeSeq = current.pending_change_seq ?? current.generated_change_seq ?? current.change_seq;
    const previous = current.retry?.change_seq === changeSeq ? current.retry : null;
    const attempts = (previous?.attempts ?? 0) + 1;
    const exhausted = attempts > SNAPSHOT_RETRY_DELAYS_MS.length;
    const now = new Date();
    const retry: WorkspaceSnapshotRetryState = {
      change_seq: changeSeq,
      attempts,
      phase: input.phase,
      next_retry_at: exhausted ? null : new Date(now.getTime() + SNAPSHOT_RETRY_DELAYS_MS[attempts - 1]).toISOString(),
      exhausted,
      last_error: input.error,
      updated_at: now.toISOString(),
    };
    return {
      next: { ...current, retry, updated_at: retry.updated_at },
      value: retry,
    };
  });
}

async function publishWorkspaceSnapshotCore(
  workspaceDir: string,
  force = false,
): Promise<MaybePublishWorkspaceSnapshotResult> {
  const workspaceId = path.basename(workspaceDir);
  if (await getWorkspaceTombstone(workspaceId)) {
    throw new Error("Workspace was deleted locally and is blocked from snapshot publication");
  }
  const files = await collectSnapshotSources(workspaceDir);
  const fingerprint = await computeSnapshotFingerprint(files, workspaceDir);
  const existing = await readSnapshotSyncState(workspaceId);
  const generationChangeSeq = existing?.change_seq ?? 0;
  const generationLifecycleEpoch = existing?.lifecycle_epoch ?? 0;
  // force bypasses the fingerprint idempotency check so the zip is rebuilt even
  // when the source tree is unchanged (e.g. a locally corrupt snapshot file must
  // be regenerated before it is re-uploaded).
  if (!force && existing?.status === "completed" &&
    existing.fingerprint_algo === SNAPSHOT_FINGERPRINT_ALGO &&
    existing.source_sha256 === fingerprint.sourceSha256) {
    // The workspace was repaired back to the exact bytes of the last verified
    // snapshot. There is nothing to rebuild or upload, but the durable
    // protection marker must no longer block a later cloud reconcile.
    if (existing.semantic_validation_failed || existing.pending_change_seq !== null) {
      await withSnapshotStateWriteLock(workspaceId, (current) => {
        const next = current.status === "completed" && current.source_sha256 === fingerprint.sourceSha256
          ? {
              ...current,
              updated_at: new Date().toISOString(),
              error: null,
              semantic_validation_failed: null,
              retry: settleSnapshotRetry(current.retry, generationChangeSeq),
              pending_change_seq: current.pending_change_seq !== null && current.pending_change_seq <= generationChangeSeq
                ? null
                : current.pending_change_seq,
            }
          : current;
        return { next, value: undefined };
      });
    }
    return {
      workspace_id: workspaceId,
      workspace_dir: workspaceDir,
      status: "skipped",
      revision: existing.revision,
      source_updated_at: existing.source_updated_at,
      source_sha256: fingerprint.sourceSha256,
      fingerprint_algo: SNAPSHOT_FINGERPRINT_ALGO,
      snapshot_path: existing.snapshot_path,
      snapshot_size_bytes: existing.snapshot_size_bytes,
      file_count: existing.file_count,
      generated_at: existing.generated_at,
    };
  }

  if (files.length === 0 || fingerprint.revision === null) {
    return {
      workspace_id: workspaceId,
      workspace_dir: workspaceDir,
      status: "skipped",
      revision: null,
      source_updated_at: null,
      source_sha256: fingerprint.sourceSha256,
      fingerprint_algo: SNAPSHOT_FINGERPRINT_ALGO,
      snapshot_path: null,
      snapshot_size_bytes: null,
      file_count: files.length,
      generated_at: null,
    };
  }

  const revision = nextSnapshotRevision(fingerprint.revision, existing?.revision);
  const attachments = await collectSnapshotAttachmentHashes(workspaceDir);
  const built = await buildSnapshotZip({
    workspaceId,
    files,
    fileDigests: fingerprint.fileDigests,
    sourceSha256: fingerprint.sourceSha256,
    sourceUpdatedAt: fingerprint.sourceUpdatedAt,
    revision,
    attachments,
  });
  // The file identity checks during archiving catch the common race, but a
  // write may still land after an entry has been queued and before its stream
  // finishes. Verify the candidate against the manifest captured *before*
  // archiving before it can replace the last known-good local package. This
  // closes the remaining "new/old files in one ZIP" window: a changed entry
  // mismatches its pre-build digest and the candidate is discarded.
  const integrityValidation = await verifyWorkspaceSnapshotZip({
    zip_path: built.zipPath,
    expected_workspace_id: workspaceId,
    expected_source_sha256: fingerprint.sourceSha256,
  });
  if (!integrityValidation.ok) {
    await unlink(built.zipPath).catch(() => undefined);
    throw new Error(`Snapshot integrity validation failed: ${integrityValidation.reason ?? "unknown error"}`);
  }
  const semanticValidation = await validateWorkspaceSnapshotZipSemantics({
    zip_path: built.zipPath,
  });
  if (!semanticValidation.ok) {
    await unlink(built.zipPath).catch(() => undefined);
    const message = `Snapshot semantic validation failed: ${semanticValidation.errors
      .map((error) => `${error.code}: ${error.message}`)
      .join("; ")}`;
    await withSnapshotStateWriteLock(workspaceId, (current) => {
      // Do not rewrite revision/source_sha256/snapshot_path here. They remain
      // the last verified snapshot, if one exists; only the candidate failure
      // is recorded. A workspace with no prior valid snapshot is explicitly
      // failed so it cannot accidentally enter the upload sweep.
      // A newer mutation or restore may have landed while the ZIP was being
      // validated. Its snapshot state must not inherit this older candidate's
      // failure or have its retry scheduling blocked by it.
      if (
        current.change_seq !== generationChangeSeq
        || current.lifecycle_epoch !== generationLifecycleEpoch
      ) {
        return { next: current, value: undefined };
      }
      return {
        next: {
          ...current,
          status: current.status === "completed" ? "completed" : "failed",
          updated_at: new Date().toISOString(),
          error: { message },
          semantic_validation_failed: {
            change_seq: generationChangeSeq,
            source_sha256: fingerprint.sourceSha256,
            source_updated_at: fingerprint.sourceUpdatedAt,
            revision,
            failed_at: new Date().toISOString(),
            errors: semanticValidation.errors,
          },
        },
        value: undefined,
      };
    });
    throw new Error(message);
  }
  const snapshotPath = path.join(snapshotFileDir(workspaceId), `${revision}.zip`);
  const epochStillCurrent = await withSnapshotStateWriteLock(workspaceId, (current) => ({
    next: current,
    value: current.lifecycle_epoch === generationLifecycleEpoch,
  }));
  if (!epochStillCurrent) {
    await unlink(built.zipPath).catch(() => undefined);
    throw new Error("Snapshot generation became stale because the Workspace was restored");
  }
  try {
    await renameWithFilesystemRetry(built.zipPath, snapshotPath);
  } catch (error) {
    await unlink(built.zipPath).catch(() => undefined);
    throw error;
  }
  const now = new Date().toISOString();
  await withSnapshotStateWriteLock(workspaceId, (current) => ({
    next: current.lifecycle_epoch !== generationLifecycleEpoch ? current : {
      ...current,
      status: "completed",
      revision,
      source_updated_at: fingerprint.sourceUpdatedAt,
      source_sha256: fingerprint.sourceSha256,
      fingerprint_algo: SNAPSHOT_FINGERPRINT_ALGO,
      snapshot_sha256: built.zipSha256,
      snapshot_path: snapshotPath,
      snapshot_size_bytes: built.sizeBytes,
      file_count: files.length,
      attachments,
      generated_at: now,
      updated_at: now,
      error: null,
      semantic_validation_failed: null,
      generated_change_seq: generationChangeSeq,
      retry: settleSnapshotRetry(current.retry, generationChangeSeq),
      pending_change_seq: current.pending_change_seq !== null && current.pending_change_seq <= generationChangeSeq
        ? null
        : current.pending_change_seq,
    },
    value: undefined,
  }));
  return {
    workspace_id: workspaceId,
    workspace_dir: workspaceDir,
    status: "generated",
    revision,
    source_updated_at: fingerprint.sourceUpdatedAt,
    source_sha256: fingerprint.sourceSha256,
    fingerprint_algo: SNAPSHOT_FINGERPRINT_ALGO,
    snapshot_path: snapshotPath,
    snapshot_size_bytes: built.sizeBytes,
    file_count: files.length,
    generated_at: now,
  };
}

/**
 * Idempotent snapshot generation. Regenerates a snapshot zip of the
 * authoritative Workspace sources only when the source fingerprint changed
 * since the last generated snapshot; otherwise it is a no-op. Errors are
 * surfaced to the caller (trigger points fire-and-forget and log them).
 */
export async function maybePublishWorkspaceSnapshot(input: {
  workspace_dir: string;
  force?: boolean;
}): Promise<MaybePublishWorkspaceSnapshotResult> {
  const normalizedDir = normalizeSnapshotWorkspaceDir(input.workspace_dir);
  const previous = workspaceSnapshotQueues.get(normalizedDir) ?? Promise.resolve();
  const current = previous
    .catch(() => undefined)
    // A restore replaces the authoritative directory. Take the same
    // workspace-level lock as generation/restore commits so collection,
    // ZIP creation and the final snapshot state cannot overlap a directory
    // swap. Direct filesystem edits remain guarded by the fingerprint's
    // before/after checks; engine-owned edits already use this lock.
    .then(() => withGenerationWorkspaceLock(
      normalizedDir,
      () => publishWorkspaceSnapshotCore(normalizedDir, input.force === true),
    ));
  workspaceSnapshotQueues.set(normalizedDir, current);
  try {
    return await current;
  } finally {
    if (workspaceSnapshotQueues.get(normalizedDir) === current) {
      workspaceSnapshotQueues.delete(normalizedDir);
    }
  }
}

export async function getWorkspaceSnapshotSyncState(input: {
  workspace_dir: string;
}): Promise<WorkspaceSnapshotSyncState | null> {
  const normalizedDir = normalizeSnapshotWorkspaceDir(input.workspace_dir);
  return readSnapshotSyncState(path.basename(normalizedDir));
}

/**
 * Record an authoritative workspace mutation before it has been represented by
 * a generated snapshot. The sequence is monotonic per workspace so a snapshot
 * generated for an older tree cannot clear a newer pending change.
 */
export async function markWorkspaceSnapshotDirty(input: {
  workspace_dir: string;
}): Promise<WorkspaceSnapshotSyncState> {
  const workspaceDir = normalizeSnapshotWorkspaceDir(input.workspace_dir);
  const workspaceId = path.basename(workspaceDir);
  if (await getWorkspaceTombstone(workspaceId)) {
    throw new Error("Workspace was deleted locally and cannot be marked dirty");
  }
  return withSnapshotStateWriteLock(workspaceId, (current) => {
    const changeSeq = current.change_seq + 1;
    const now = new Date().toISOString();
    const invalidatesSemanticFailure = current.semantic_validation_failed !== null
      && current.semantic_validation_failed.change_seq < changeSeq;
    const next: WorkspaceSnapshotSyncState = {
      ...current,
      change_seq: changeSeq,
      pending_change_seq: changeSeq,
      retry: null,
      // A new committed tree supersedes diagnostics for an older rejected ZIP.
      // Keep only failures that could still belong to this exact sequence.
      semantic_validation_failed: invalidatesSemanticFailure ? null : current.semantic_validation_failed,
      error: invalidatesSemanticFailure ? null : current.error,
      updated_at: now,
    };
    return { next, value: next };
  });
}

